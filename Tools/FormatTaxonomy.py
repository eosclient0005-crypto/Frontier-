def EmitToml(path):
    lines = ["# Frontier format suffix registry -- GENERATED by Tools/FormatTaxonomy.py",
             "# Do not hand-edit: change the table in Tools/FormatTaxonomy.py and regenerate.",
             "", "[meta]", f'space_roster = [{", ".join(chr(34) + s + chr(34) for s in SPACE_DOMAINS)}]', ""]
    for group, entries in GROUPS:
        lines.append(f"# {'-' * 78}\n# {group}\n# {'-' * 78}\n")
        for e in entries:
            lines.append(f"[[format]]")
            lines.append(f'id = "{e["id"]}"')
            lines.append(f'group = "{group}"')
            lines.append(f'concept = "{e["concept"]}"')
            lines.append(f'chosen = "{e["chosen"]}"')
            for key in ("candidates", "aliases"):
                vals = ", ".join(f'"{v}"' for v in e[key])
                lines.append(f"{key} = [{vals}]")
            lines.append(f'codec = "{e["codec"]}"')
            lines.append(f'unit = "{e["unit"]}"')
            lines.append(f'note = "{e["note"]}"')
            lines.append("")
    for name, chosen, candidates, legacy in CONTAINMENT_FIELDS:
        lines.append("[[containment]]")
        lines.append(f'field = "{name}"')
        lines.append(f'chosen = "{chosen}"')
        lines.append(f'candidates = [{", ".join(chr(34) + c + chr(34) for c in candidates)}]')
        lines.append(f'legacy_replaced = [{", ".join(chr(34) + c + chr(34) for c in legacy)}]')
        lines.append("")
    for name, key, desc, legacy in ROOT_DOCUMENTS:
        lines.append("[[root_document]]")
        lines.append(f'suffix = "{name}"')
        lines.append(f'description = "{desc}"')
        lines.append(f'legacy_replaced = "{legacy}"')
        lines.append("")
    path.write_text("\n".join(lines) + "\n")


def EmitLedger(path):
    out = ["# Frontier Format Candidate Ledger",
           "",
           "> GENERATED by `Tools/FormatTaxonomy.py` -- regenerate instead of editing.",
           "> Every row: the concept, the chosen name, **five or more alternatives**, the owning codec,",
           "> the legacy suffixes it still decodes, and the bare name to use under the strict roster.",
           "",
           "**Reading the columns** — *Chosen* is the recommendation. *Bare variant* is the name to adopt",
           "if the strict four-domain `Space` roster (`Geometry` · `Particles` · `Physics` · `Audio`) is",
           "selected instead of the extended ten-domain one. Every candidate in this ledger passed",
           "`Tools/NamingAudit.py`, so any of them is safe to adopt without re-litigating the blacklist.",
           ""]
    for group, entries in GROUPS:
        out.append(f"\n## {group}\n")
        out.append("| Concept | Chosen | Five or more alternatives | Bare variant | Owning codec | Engine unit | Legacy read-aliases | Rationale |")
        out.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
        for e in entries:
            alts = " · ".join(f"`{c}`" for c in e["candidates"] if c != e["chosen"])
            aliases = " · ".join(f"`{a}`" for a in e["aliases"]) or "—"
            out.append(f"| {e['concept']} | **`{e['chosen']}`** | {alts} | {e['bare']} | `{e['codec']}` | "
                       f"`{e['unit']}` | {aliases} | {e['note'] or '—'} |")
    out.append("\n## Containment Link Fields (kinship and `peer` retired)\n")
    out.append("| Field | Chosen | Alternatives | Retired (kinship / `peer`) |")
    out.append("| :--- | :--- | :--- | :--- |")
    for name, chosen, candidates, legacy in CONTAINMENT_FIELDS:
        alts = " · ".join(f"`{c}`" for c in candidates if c != chosen) or "—"
        out.append(f"| {name} | **`{chosen}`** | {alts} | {' · '.join(f'`{c}`' for c in legacy)} |")
    out.append("\n## Engine Root Documents\n")
    out.append("| Chosen suffix | Owner unit | Holds | Replaces |")
    out.append("| :--- | :--- | :--- | :--- |")
    for suffix, key, desc, legacy in ROOT_DOCUMENTS:
        out.append(f"| **`{suffix}`** | `{key}Codec` | {desc} | {legacy} |")
    out.append("")
    path.write_text("\n".join(out) + "\n")


